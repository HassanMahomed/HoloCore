"""Generate a read-only Obsidian vault view of every registered World."""
from __future__ import annotations

import hashlib
import json
import re
from pathlib import Path
from typing import Any

from .global_graph import build_global_graph

VAULT_NAME = "HoloCore Obsidian Vault"
GENERATED_MARKER = "<!-- Generated by HoloCore; do not edit. -->"


def _slug(value: str) -> str:
    value = re.sub(r"[^A-Za-z0-9._-]+", "-", str(value)).strip("-._") or "signal"
    return value[:80]


def _note_slug(node: dict[str, Any]) -> str:
    identity = str(node.get("id", "signal"))
    digest = hashlib.sha1(identity.encode("utf-8")).hexdigest()[:10]
    return f"{_slug(str(node.get('label') or identity))}-{digest}"


def _write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content.rstrip() + "\n", encoding="utf-8")


def build_obsidian_vault(home: str | Path, *, output: str | Path | None = None) -> dict[str, Any]:
    """Build one Obsidian-readable, generated view across all World Atlases."""
    home_path = Path(home).expanduser().resolve()
    destination = Path(output).expanduser().resolve() if output else home_path / VAULT_NAME
    graph = build_global_graph(home_path)
    nodes = [node for node in graph.get("nodes", []) if isinstance(node, dict)]
    world_nodes = {str(node["world"]): node for node in nodes if node.get("kind") == "world" and node.get("world")}
    note_paths: dict[str, str] = {}
    for node in nodes:
        node_id = str(node.get("id", ""))
        if node.get("kind") == "world":
            note_paths[node_id] = f"Worlds/{_slug(str(node.get('world') or node.get('label') or node_id))}"
        elif node_id:
            world = _slug(str(node.get("world") or "Unassigned"))
            note_paths[node_id] = f"Worlds/{world}/Signals/{_note_slug(node)}"

    links_by_source: dict[str, list[dict[str, Any]]] = {}
    for edge in graph.get("links", []):
        source = str(edge.get("source", "")); target = str(edge.get("target", ""))
        if source in note_paths and target in note_paths:
            links_by_source.setdefault(source, []).append(edge)

    _write(destination / "README.md", f"""{GENERATED_MARKER}
# HoloCore Obsidian Vault

Open this folder as an Obsidian vault to see the structural graph of every registered HoloCore World.

This is a generated, read-only view. Source project files, World Atlases, Archive notes, and Animus data remain in their original locations.

- [[system/index|Start here]]
- Generated from the Atlas-only cross-World graph.
- Run `holocore obsidian-vault` to refresh this view.
""")
    _write(destination / "system" / "index.md", f"""{GENERATED_MARKER}
# HoloCore World Atlas

One Obsidian graph across all registered projects. Each World owns its generated component notes; links between components create the graph edges.

## Worlds

""" + "\n".join(f"- [[{note_paths[node_id]}|{node.get('label', world_id)}]]" for world_id, node in sorted(world_nodes.items()) for node_id in [str(node["id"])]) + "\n\n## Safety\n\nThis vault is generated from Atlas JSON. It is not an Archive source and is never used as an Atlas input.\n")

    for world_id, world_node in sorted(world_nodes.items()):
        world_node_id = str(world_node["id"])
        child_nodes = [node for node in nodes if node.get("world") == world_id and node.get("kind") != "world"]
        links = "\n".join(f"- [[{note_paths[str(node['id'])]}|{node.get('label', node['id'])}]]" for node in child_nodes if str(node.get("id")) in note_paths)
        _write(destination / f"{note_paths[world_node_id]}.md", f"""{GENERATED_MARKER}
# {world_node.get('label', world_id)}

World ID: `{world_id}`

## Components

{links or '- No Atlas components were found.'}
""")

    for node in nodes:
        node_id = str(node.get("id", ""))
        if not node_id or node.get("kind") == "world" or node_id not in note_paths:
            continue
        outgoing = links_by_source.get(node_id, [])
        relationship_lines = []
        for edge in outgoing:
            target = str(edge.get("target", ""))
            relation = str(edge.get("relation") or edge.get("type") or "related")
            if target in note_paths:
                relationship_lines.append(f"- {relation}: [[{note_paths[target]}]]")
        world_id = _slug(str(node.get("world") or "Unassigned"))
        _write(destination / f"{note_paths[node_id]}.md", f"""{GENERATED_MARKER}
# {node.get('label', node_id)}

- World: [[Worlds/{world_id}|{node.get('world', 'Unassigned')}]]
- Kind: `{node.get('kind', 'signal')}`
- Source file: `{node.get('source_file', '')}`
- Source location: `{node.get('source_location', '')}`

## Relationships

{chr(10).join(relationship_lines) or '- No outgoing Atlas relationships.'}
""")

    _write(destination / "system" / "atlas-manifest.json", json.dumps({
        "generator": "holocore-obsidian-vault",
        "source": "Atlas-only; Archive and Animus remain World-owned",
        "home": str(home_path),
        "worlds": sorted(world_nodes),
        "nodes": len(nodes),
        "links": len(graph.get("links", [])),
    }, indent=2, sort_keys=True))
    return {"path": str(destination), "vault_name": VAULT_NAME, "worlds": len(world_nodes), "nodes": len(nodes), "links": len(graph.get("links", []))}


__all__ = ["VAULT_NAME", "build_obsidian_vault"]
